#!/usr/bin/env node
// web/ -> extensions/dashboard.generated.ts
//
// The dashboard is one HTML string that the extension serves at GET /. Keeping it in
// web/ means it is edited, diffed and linted as HTML instead of living inside a
// template literal in the middle of a 3,800-line module.
//
// No bundler: the output is a single template literal, so the escape order matters.
// Backslashes go first, then backticks and $, otherwise an escaped backtick would
// come out as a double backslash and break the literal.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const BT = String.fromCharCode(96);
const GEN = join(root, "extensions", "dashboard.generated.ts");

// CRLF and stray CR are normalised here, not at comparison time: the generated
// literal must be identical whatever the checkout did to the working tree.
export const normalise = (s) => s.replace(/\r\n?/g, "\n");
const read = (f) => normalise(readFileSync(join(root, "web", f), "utf8"));

export function buildWeb() {
	// Inline the two shared scripts. The function replacer keeps "$&" and friends in
	// the payload from being read as substitution patterns.
	const html = read("dashboard.html")
		.replace("__KB_MD_JS__", () => read("md.js").trim())
		.replace("__KB_MEMORY_JS__", () => read("memory.js").trim());
	const left = html.match(/__KB_(MD_JS|MEMORY_JS)__/g);
	if (left) throw new Error("build-web: placeholder left in the page: " + left.join(", "));

	const body = html
		.replace(/\\/g, "\\\\")
		.replace(/`/g, "\\`")
		.replace(/\$\{/g, "\\${");

	return (
		"// GENERATED by scripts/build-web.mjs from web/dashboard.html - do not edit.\n" +
		"// Run `npm run build` after changing the HTML.\n" +
		"export const DASHBOARD_TEMPLATE = " + BT + body + BT + ";\n"
	);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const want = buildWeb();
	if (process.argv.includes("--check")) {
		if (normalise(readFileSync(GEN, "utf8")) !== want) {
			console.error("build-web: extensions/dashboard.generated.ts is stale - run `npm run build`");
			process.exit(1);
		}
		console.log("build-web: up to date");
	} else {
		writeFileSync(GEN, want, "utf8");
		console.log("build-web: " + want.length + " chars -> extensions/dashboard.generated.ts");
	}
}
